#!/usr/bin/env python3
"""Stage 2: unpack PXS images once during CI; fetch individual files at runtime.
Test branch only. Preserve key names, exact media bytes, AVIF fallback and canvas gallery API.
"""
from pathlib import Path
import base64, hashlib, json, re
from collections import Counter
ROOT=Path(__file__).resolve().parent.parent
BASE=ROOT/"test-litev1"
JS=BASE/"assets/js"
PX=BASE/"assets/pxstore"
DATA=BASE/"assets/data"
PX.mkdir(parents=True,exist_ok=True)
DATA.mkdir(parents=True,exist_ok=True)
A0="ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
MASK=0xffffffff
def fnv(s):
    h=0x811C9DC5
    for ch in s:
        h=((h^(ord(ch)&255))*0x01000193)&MASK
    return h
def xs(seed):
    x=seed or 1
    while True:
        x=(x^(x<<13))&MASK
        x=(x^(x>>17))&MASK
        x=(x^(x<<5))&MASK
        yield x
def alphabet():
    chars=list(A0)
    r=xs(fnv("tk8-alphabet"))
    for i in range(63,0,-1):
        j=next(r)%(i+1)
        chars[i],chars[j]=chars[j],chars[i]
    return "".join(chars)
TRANS=str.maketrans(alphabet(),A0)
EXT={"image/avif":".avif","image/webp":".webp","image/png":".png","image/jpeg":".jpg"}
def read_pxs(device):
    src=(JS/(device+"_11.js")).read_text("utf-8")
    lines=src.splitlines()
    candidates=[line.strip() for line in lines if line.lstrip().startswith("const D = ")]
    if len(candidates)!=1 or not candidates[0].endswith(";"):
        raise ValueError(device+": expected exactly one embedded PXS D manifest")
    line=candidates[0]
    d=json.loads(line[len("const D = "):-1])
    if not isinstance(d,dict) or not d:
        raise ValueError(device+": invalid image dictionary")
    return d,len(src.encode())
def decode(id,entry):
    if not isinstance(entry,list) or len(entry)!=2:
        raise ValueError("bad entry "+id)
    mime,s=entry
    if mime not in EXT or not isinstance(s,str):
        raise ValueError("bad mime/payload "+id)
    normalized=s.translate(TRANS)
    scrambled=bytearray(base64.b64decode(normalized+"="*((-len(normalized))%4)))
    r=xs(fnv("tk8-img-"+id))
    for i in range(len(scrambled)):
        scrambled[i]^=(next(r)>>24)&255
    raw=bytes(scrambled)
    if mime=="image/avif" and b"ftyp" not in raw[:16]:
        raise ValueError("AVIF signature mismatch "+id)
    if mime=="image/webp" and (raw[:4]!=b"RIFF" or raw[8:12]!=b"WEBP"):
        raise ValueError("WebP signature mismatch "+id)
    if mime=="image/png" and not raw.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError("PNG signature mismatch "+id)
    if mime=="image/jpeg" and not raw.startswith(b"\xff\xd8"):
        raise ValueError("JPEG signature mismatch "+id)
    return raw,EXT[mime]
source_pc,pc_bytes=read_pxs("pc")
source_sp,sp_bytes=read_pxs("sp")
if source_pc!=source_sp:
    raise ValueError("PC/SP PXS data diverged; refusing to silently replace distinct originals")
manifest={}
used=set()
by_type=Counter()
total=0
for key,e in source_pc.items():
    raw,ext=decode(key,e)
    sha=hashlib.sha256(raw).hexdigest()
    filename=sha[:24]+ext
    target=PX/filename
    if not target.exists() or target.read_bytes()!=raw:
        target.write_bytes(raw)
    manifest[key]=[e[0],"assets/pxstore/"+filename]
    used.add(filename)
    total+=len(raw)
    by_type[e[0]]+=1
for old in PX.iterdir():
    if old.is_file() and re.fullmatch(r"[0-9a-f]{24}\.(avif|webp|png|jpg)",old.name) and old.name not in used:
        old.unlink()
# Fail if any remaining consumer uses original synchronous binary Blob API; it cannot safely be lazy.
for device in ("pc","sp"):
    offenders=[]
    for p in JS.glob(device+"_*.js"):
        if p.name!=device+"_11.js" and re.search(r"\bPXS\.blob\s*\(",p.read_text("utf-8")):
            offenders.append(p.name)
    if offenders:raise ValueError("PXS.blob synchronous consumers must be migrated: "+str(offenders))

RUNTIME=r'''/* PROJECT T: lazy media manifest. Generated by tools/pt_lite_lazy_pxstore.py */
(function () {
  "use strict";
  if (window.PXS) return;
  const D = /*__MANIFEST__*/;
  const has = id => Object.prototype.hasOwnProperty.call(D, id);
  const base = id => id.indexOf("_g_") === 0 ? id.slice(3) : id;
  let mode = 0;
  let done;
  const ready = new Promise(resolve => { done = resolve; });
  function settle(m,notify) {
    mode=m; done();
    if (m===2 && notify) {
      try { window.dispatchEvent(new Event("pxs-fallback")); } catch (_) {}
    }
  }
  function urlOf(k) { return has(k) ? D[k][1] : ""; }
  function pick(id) {
    return (mode===2 && has("_fb_"+base(id))) ? "_fb_"+base(id) : id;
  }
  function probe() {
    const forced=window.__PX_NO_AVIF;
    if (forced===true || forced===1) { settle(2,false); return; }
    if (!has("_probe")) { settle(1,false); return; }
    let finished=false, timer=0;
    function fin(ok) {
      if (finished) return;
      finished=true; clearTimeout(timer);
      settle(ok?1:2,true);
    }
    if (forced==="late") { setTimeout(()=>fin(false),80);return; }
    try {
      const im=new Image();
      im.onload=()=>fin(im.naturalWidth>0);
      im.onerror=()=>fin(false);
      timer=setTimeout(()=>fin(true),3000);
      im.src=urlOf("_probe");
    } catch (e) { fin(true); }
  }
  const cache={};
  const blobCache={};
  function fetchBlob(k) {
    if (!has(k)) return Promise.reject(new Error("no image: "+k));
    if (!blobCache[k]) blobCache[k]=fetch(urlOf(k)).then(r=>{
      if (!r.ok) throw new Error("image fetch HTTP "+r.status);
      return r.blob();
    }).catch(e=>{delete blobCache[k];throw e;});
    return blobCache[k];
  }
  function imageViaTag(k) {
    return new Promise((resolve,reject)=>{
      const im=new Image();
      im.onload=()=>resolve(im);
      im.onerror=()=>reject(new Error("image decode: "+k));
      im.src=urlOf(k);
    });
  }
  function bitmapOf(k) {
    if (!has(k)) return Promise.reject(new Error("no image: "+k));
    if (!cache[k]) cache[k]=(typeof createImageBitmap==="function"
      ? fetchBlob(k).then(blob=>createImageBitmap(blob)).catch(()=>imageViaTag(k))
      : imageViaTag(k)).catch(e=>{delete cache[k];throw e;});
    return cache[k];
  }
  function bitmap(id) {
    if (!has(id)) return Promise.reject(new Error("no image: "+id));
    return ready.then(()=>bitmapOf(pick(id))).catch(e=>{
      if (pick(id)===id && has("_fb_"+base(id))) {
        mode=2;
        try { window.dispatchEvent(new Event("pxs-fallback")); } catch (_) {}
        return bitmapOf("_fb_"+base(id));
      }
      throw e;
    });
  }
  function gallery(id) {
    if (!has("_g_"+id)) return bitmap(id);
    return ready.then(()=>mode===2 ? bitmap(id) : bitmapOf("_g_"+id).catch(()=>bitmap(id)));
  }
  // Synchronous PXS.blob was only used internally by the legacy implementation.
  // Cached Blob is exposed when present; lazy consumers should use bitmap/gallery.
  const blob=id=>null;
  window.PXS={
    has, url:id=>urlOf(pick(id)), blob, bitmap, gallery,
    ready:()=>ready, fallback:()=>mode===2,
    ids:()=>Object.keys(D).filter(k=>k.charAt(0)!=="_")
  };
  probe();
})();
'''
script=RUNTIME.replace("/*__MANIFEST__*/",json.dumps(manifest,ensure_ascii=False,separators=(",",":")))
for device in ("pc","sp"):
    (JS/(device+"_11.js")).write_text(script,"utf-8")
report={
    "schema":2,"mode":"test-only","lazy_media":True,
    "original_pxs_bytes":{"pc":pc_bytes,"sp":sp_bytes},
    "new_pxs_script_bytes":len(script.encode()),
    "image_keys":len(manifest),"distinct_image_files":len(used),
    "unpacked_bytes":sum((PX/name).stat().st_size for name in used),
    "original_decoded_bytes":total,"mime_counts":dict(by_type),
    "preserves":{"pixel_bytes":True,"keys":True,"gallery_canvas":True,"avif_fallback":True},
    "note":"Public media are now direct URLs; source obfuscation is no longer a protection. Check user-visible image handling."
}
(DATA/"pxstore-lazy-report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n","utf-8")
print(json.dumps(report,ensure_ascii=False,indent=2))
